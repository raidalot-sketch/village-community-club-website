ALTER TABLE club_posts ADD COLUMN IF NOT EXISTS summary TEXT NULL;
ALTER TABLE club_posts ADD COLUMN IF NOT EXISTS cover_attachment_id INT UNSIGNED NULL;
CREATE TABLE IF NOT EXISTS club_editor_sessions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 post_id INT UNSIGNED NULL,
 token_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(user_id,post_id),
 FOREIGN KEY(user_id) REFERENCES club_users(id) ON DELETE CASCADE,
 FOREIGN KEY(post_id) REFERENCES club_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
