CREATE TABLE IF NOT EXISTS club_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, phone VARCHAR(40) NOT NULL DEFAULT '', status ENUM('pending','active','suspended') NOT NULL DEFAULT 'active',
 email_verified_at DATETIME NULL, last_login_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_user_roles (
 user_id INT UNSIGNED NOT NULL, role ENUM('member','publisher','treasurer','administrator') NOT NULL,
 PRIMARY KEY(user_id,role), FOREIGN KEY(user_id) REFERENCES club_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_memberships (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, status ENUM('awaiting_payment','active','expired','suspended','cancelled') NOT NULL DEFAULT 'awaiting_payment',
 starts_on DATE NULL, expires_on DATE NULL, invoice_public_id VARCHAR(100) NULL, external_ref VARCHAR(190) NOT NULL UNIQUE,
 amount_minor INT UNSIGNED NULL, currency CHAR(3) NOT NULL DEFAULT 'GBP', payment_reference VARCHAR(100) NULL,
 confirmed_by INT UNSIGNED NULL, confirmed_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(user_id,status), FOREIGN KEY(user_id) REFERENCES club_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_posts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, author_user_id INT UNSIGNED NOT NULL, title VARCHAR(190) NOT NULL,
 slug VARCHAR(210) NOT NULL UNIQUE, content MEDIUMTEXT NOT NULL, status ENUM('draft','submitted','published','rejected') NOT NULL DEFAULT 'draft',
 reviewer_note TEXT NULL, approved_by INT UNSIGNED NULL, published_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(author_user_id) REFERENCES club_users(id), INDEX(status,published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_revisions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, owner_type VARCHAR(30) NOT NULL, owner_id INT UNSIGNED NOT NULL,
 author_user_id INT UNSIGNED NOT NULL, payload JSON NOT NULL, status ENUM('submitted','approved','rejected') NOT NULL DEFAULT 'submitted',
 reviewer_note TEXT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(owner_type,owner_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_polls (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, author_user_id INT UNSIGNED NOT NULL, title VARCHAR(255) NOT NULL,
 description TEXT NULL, opens_at DATETIME NOT NULL, closes_at DATETIME NOT NULL,
 status ENUM('draft','submitted','published','rejected','cancelled') NOT NULL DEFAULT 'draft', reviewer_note TEXT NULL,
 approved_by INT UNSIGNED NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, FOREIGN KEY(author_user_id) REFERENCES club_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_poll_choices (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, poll_id INT UNSIGNED NOT NULL, label VARCHAR(255) NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 UNIQUE(poll_id,id), FOREIGN KEY(poll_id) REFERENCES club_polls(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_poll_votes (
 poll_id INT UNSIGNED NOT NULL, user_id INT UNSIGNED NOT NULL, choice_id INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(poll_id,user_id), FOREIGN KEY(poll_id,choice_id) REFERENCES club_poll_choices(poll_id,id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES club_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_attachments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, owner_type VARCHAR(30) NOT NULL, owner_id INT UNSIGNED NOT NULL, user_id INT UNSIGNED NULL,
 storage_path VARCHAR(255) NOT NULL, original_name VARCHAR(190) NOT NULL, mime VARCHAR(100) NOT NULL, bytes INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(owner_type,owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_enquiry_routes (
 user_id INT UNSIGNED NOT NULL, category VARCHAR(30) NOT NULL, PRIMARY KEY(user_id,category), FOREIGN KEY(user_id) REFERENCES club_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_outbox (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, channel VARCHAR(30) NOT NULL, event_key VARCHAR(190) NOT NULL UNIQUE, payload JSON NOT NULL,
 status ENUM('pending','processing','sent','failed','connection_required') NOT NULL DEFAULT 'pending', attempts INT UNSIGNED NOT NULL DEFAULT 0,
 remote_id VARCHAR(190) NULL, last_error VARCHAR(500) NULL, available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_payment_events (
 event_id VARCHAR(190) PRIMARY KEY, membership_id INT UNSIGNED NOT NULL, payload_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS club_password_tokens (
 token_hash CHAR(64) PRIMARY KEY, user_id INT UNSIGNED NOT NULL, purpose ENUM('verify','reset') NOT NULL,
 expires_at DATETIME NOT NULL, consumed_at DATETIME NULL, FOREIGN KEY(user_id) REFERENCES club_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
